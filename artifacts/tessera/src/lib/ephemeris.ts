export function computeMoonState(dateMs: number): MoonState {
  const T = (dateMs - J2000_MS) / (36525 * 86400000); // Julian centuries

  // Meeus Ch.47 fundamental arguments
  const D  = norm360(297.8501921 + 445267.1114034 * T - 0.0018819 * T * T + T * T * T / 545868);
  const M  = norm360(357.5291092 + 35999.0502909  * T - 0.0001536 * T * T + T * T * T / 24490000);
  const Mp = norm360(134.9633964 + 477198.8676313 * T + 0.0089970 * T * T + T * T * T / 69699 - T * T * T * T / 14712000);
  const F  = norm360(93.2720950  + 483202.0175233 * T - 0.0036539 * T * T - T * T * T / 3526000 + T * T * T * T / 863310000);
  const A1 = norm360(119.75 + 131.849 * T);
  const A2 = norm360(53.09  + 479264.290 * T);
  const A3 = norm360(313.45 + 481266.484 * T);
  const E  = 1 - 0.002516 * T - 0.0000074 * T * T;

  const Dr = D * DEG, Mr = M * DEG, Mpr = Mp * DEG, Fr = F * DEG;
  const A1r = A1 * DEG, A2r = A2 * DEG, A3r = A3 * DEG;

  // Lp = Moon's mean longitude (computed first, needed for additive corrections)
  const Lp = norm360(218.3164477 + 481267.88123421 * T - 0.0015786 * T * T + T * T * T / 538841 - T * T * T * T / 65194000);

  // Sum longitude & distance corrections
  let sumL = 0, sumR = 0;
  for (const [dD, dM, dMp, dF, cl, cr] of ELP_LR) {
    const arg = dD * Dr + dM * Mr + dMp * Mpr + dF * Fr;
    let coeff = 1;
    if (Math.abs(dM) === 1) coeff = E;
    if (Math.abs(dM) === 2) coeff = E * E;
    sumL += coeff * cl * Math.sin(arg);
    sumR += coeff * cr * Math.cos(arg);
  }

  // Additive corrections to longitude (Meeus Ch.47, after Eq.47.1)
  sumL += 3958 * Math.sin(A1r)
        + 1962 * Math.sin((Lp - F) * DEG)   // Venus perturbation
        +  318 * Math.sin(A2r);

  // Sum latitude corrections
  let sumB = 0;
  for (const [dD, dM, dMp, dF, cb] of ELP_B) {
    const arg = dD * Dr + dM * Mr + dMp * Mpr + dF * Fr;
    let coeff = 1;
    if (Math.abs(dM) === 1) coeff = E;
    if (Math.abs(dM) === 2) coeff = E * E;
    sumB += coeff * cb * Math.sin(arg);
  }
  sumB += -2235 * Math.sin(Mp * DEG)
          +  382 * Math.sin(A3r)
          +  175 * Math.sin((A1 - F) * DEG)
          +  175 * Math.sin((A1 + F) * DEG)
          +  127 * Math.sin((Mp - M) * DEG)
          -  115 * Math.sin((Mp + M) * DEG);

  const lon = norm360(Lp + sumL / 1000000);
  const lat = sumB / 1000000;
  const distKm = 385000.56 + sumR / 1000;

  // Phase
  const sunLon = computeSunLongitude(dateMs);
  const elongation = norm360(lon - sunLon);
  const phaseAngle = 180 - elongation;
  const illumination = Math.round((1 + Math.cos(phaseAngle * DEG)) / 2 * 10000) / 100;

  const knownNewMoon = 2451550.1;
  const jd = toJulianDay(dateMs);
  const synodicMonth = 29.53059;
  const lunarAge = ((jd - knownNewMoon) % synodicMonth + synodicMonth) % synodicMonth;

  const phaseIndex = Math.floor(elongation / 45) % 8;

  return {
    lon,
    lat,
    distanceKm: Math.round(distKm),
    phaseAngle,
    illumination,
    phaseName:  MOON_PHASE_NAMES[phaseIndex],
    phaseEmoji: MOON_PHASE_EMOJI[phaseIndex],
    lunarAge:   Math.round(lunarAge * 100) / 100,
  };
}

