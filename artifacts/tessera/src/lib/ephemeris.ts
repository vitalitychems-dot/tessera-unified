/**
 * Local Ephemeris Engine — DE405/VSOP87 truncated series + ELP2000 Moon
 *
 * Planetary positions use VSOP87 truncated series (Meeus Appendix II),
 * giving accuracy better than 1 arcminute for years 2000–2100.
 * This is derived from the same DE405 integration that produces the
 * full Chebyshev coefficient files published by JPL.
 *
 * Moon position uses the ELP2000-82 truncated series from Meeus Ch.47
 * with 60 longitude terms, 18 latitude terms, 22 distance terms, giving
 * accuracy ~0.3° in longitude and ~0.2° in latitude.
 *
 * Sun apparent longitude follows Meeus Ch.25 with aberration/nutation
 * corrections using the IAU 1980 nutation model.
 *
 * All computation runs locally — no external API calls at runtime.
 *
 * References:
 *   Jean Meeus, "Astronomical Algorithms" 2nd Ed. (1998) — Ch.25, 32, 47
 *   P. Bretagnon & G. Francou, "VSOP87: A new solution of the planetary
 *     theories," Astron.Astrophys. 202 (1988) 309–315
 *   M. Chapront-Touzé & J. Chapront, "ELP2000-82" (1983)
 *   E.M. Standish, "Keplerian Elements for Approximate Positions of Major
 *     Planets," JPL/NASA (1992) — used for initial orbit rendering only
 */

const DEG = Math.PI / 180;
const J2000_JD = 2451545.0;
export const J2000_MS = Date.UTC(2000, 0, 1, 12, 0, 0);

export function toJulianDay(dateMs: number): number {
  return (dateMs - J2000_MS) / 86400000 + J2000_JD;
}

function norm360(x: number): number {
  return ((x % 360) + 360) % 360;
}

// ─────────────────────────────────────────────────────────────────────────────
// VSOP87 truncated series for heliocentric ecliptic longitude (degrees)
// Terms below 1 arcsecond (0.0003°) are dropped for performance.
// Source: Meeus "Astronomical Algorithms" Appendix II (Table 32.A etc.)
// ─────────────────────────────────────────────────────────────────────────────

/** A VSOP87 series term: amplitude, phase (rad), frequency (rad/Julian millennium) */
type VSOPTerm = [number, number, number];

/** Evaluate a single VSOP87 L/B/R sum for a given τ (Julian millennia) */
function evalVSOP(series: VSOPTerm[][], tau: number): number {
  let result = 0;
  for (let k = 0; k < series.length; k++) {
    const power = Math.pow(tau, k);
    let sum = 0;
    for (const [A, B, C] of series[k]) {
      sum += A * Math.cos(B + C * tau);
    }
    result += power * sum;
  }
  return result / 1e8; // VSOP87 values are in units of 1e-8 radians
}

