function solveKepler(M: number, e: number): number {
  let E = M;
  for (let i = 0; i < 50; i++) {
    const dE = (M - E + e * Math.sin(E)) / (1 - e * Math.cos(E));
    E += dE;
    if (Math.abs(dE) < 1e-12) break;
  }
  return E;
}

export function computeAsteroidPosition(ast: AsteroidDef, dateMs: number): EclipticCoords {
  const T = (dateMs - J2000_MS) / (36525 * 86400000);
  const a = ast.a, e = ast.e;
  const I = ast.I * DEG;
  const L = norm360(ast.L0 + ast.LD * T);
  const wBar = norm360(ast.w0);
  const O = norm360(ast.O0);
  const M = norm360(L - wBar) * DEG;
  const w = norm360(wBar - O) * DEG;
  const Oi = O * DEG;
  const E = solveKepler(M, e);
  const xp = a * (Math.cos(E) - e), yp = a * Math.sqrt(1 - e * e) * Math.sin(E);
  const cosw = Math.cos(w), sinw = Math.sin(w);
  const cosO = Math.cos(Oi), sinO = Math.sin(Oi), cosI = Math.cos(I);
  const x = (cosw * cosO - sinw * sinO * cosI) * xp + (-sinw * cosO - cosw * sinO * cosI) * yp;
  const y = (cosw * sinO + sinw * cosO * cosI) * xp + (-sinw * sinO + cosw * cosO * cosI) * yp;
  return { x, y, lon: norm360(Math.atan2(y, x) / DEG), r: Math.sqrt(x * x + y * y) };
}

