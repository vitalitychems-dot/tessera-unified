// ─────────────────────────────────────────────────────────────────────────────
// Public: compute heliocentric ecliptic position (VSOP87-derived)
// ─────────────────────────────────────────────────────────────────────────────

export interface EclipticCoords {
  x: number;    // AU heliocentric, ecliptic J2000
  y: number;    // AU
  lon: number;  // ecliptic longitude (deg, 0–360)
  r: number;    // heliocentric distance (AU)
}

export function computePlanetPosition(name: string, dateMs: number): EclipticCoords {
  const tau = (dateMs - J2000_MS) / (365250 * 86400000); // Julian millennia
  const lSeries = VSOP_SERIES[name];
  const rSeries = VSOP_R[name];

  if (!lSeries || !rSeries) throw new Error(`Unknown planet: ${name}`);

  const L = norm360(evalVSOP(lSeries, tau) / DEG);   // degrees
  const r = evalVSOP(rSeries, tau) / 1e8;             // override raw; need separate eval

  // Evaluate distance
  let rAU = 0;
  for (let k = 0; k < rSeries.length; k++) {
    let sum = 0;
    for (const [A, B, C] of rSeries[k]) sum += A * Math.cos(B + C * tau);
    rAU += Math.pow(tau, k) * sum;
  }
  rAU /= 1e8;

  const lRad = L * DEG;
  const x = rAU * Math.cos(lRad);
  const y = rAU * Math.sin(lRad);

  return { x, y, lon: L, r: Math.abs(rAU) };
}

// ─────────────────────────────────────────────────────────────────────────────
// Sun geocentric apparent longitude (Meeus Ch.25)
// ─────────────────────────────────────────────────────────────────────────────

export function computeSunLongitude(dateMs: number): number {
  const tau = (dateMs - J2000_MS) / (365250 * 86400000);
  // Heliocentric Earth longitude → geocentric Sun longitude = +180°
  const earthL = evalVSOP(VSOP_EARTH_L, tau) / DEG;
  const theta = norm360(earthL + 180);
  // Aberration correction (~−20.4898″/R, R ≈ 1 AU)
  const T = tau * 10; // Julian centuries
  const omega = norm360(125.04 - 1934.136 * T);
  return norm360(theta - 0.00569 - 0.00478 * Math.sin(omega * DEG));
}

