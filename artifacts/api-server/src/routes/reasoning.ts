router.post("/reasoning/counterfactual", async (req, res) => {
  try {
    const { modelId, query } = req.body;
    if (!modelId || !query) return res.status(400).json({ error: "modelId and query are required" });

    const [model] = await db.select().from(causalModelsTable).where(eq(causalModelsTable.id, modelId));
    if (!model) return res.status(404).json({ error: "Causal model not found" });

    const nodes = model.nodes as any[];
    const edges = model.edges as any[];
    const avgEdgeStrength = edges.length > 0
      ? edges.reduce((s: number, e: any) => s + (e.strength ?? 0.5), 0) / edges.length
      : 0.5;
    const graphDensity = nodes.length > 0 ? Math.min(1, edges.length / (nodes.length * 2)) : 0;
    const queryComplexity = Math.min(1, query.split(/\s+/).length / 30);

    const { getAllProviderProfiles } = await import("../lib/provider-registry");
    const profiles = await getAllProviderProfiles();
    const avgProviderReliability = profiles.length > 0
      ? profiles.reduce((s: number, p: any) => s + (p.reliabilityScore ?? 50), 0) / profiles.length / 100
      : 0.5;

    const computedConfidence = Math.round(
      (avgEdgeStrength * 0.4 + graphDensity * 0.25 + (1 - queryComplexity) * 0.15 + avgProviderReliability * 0.2) * 100
    ) / 100;

    const newCounterfactual = {
      query,
      analysis: `Counterfactual analysis for "${query.slice(0, 80)}": ` +
        `Intervening at this point in the ${model.domain} causal chain would propagate through ${nodes.length} nodes. ` +
        `The primary effect pathway would be altered, with cascading consequences across ${edges.length} causal edges. ` +
        `Confidence derived from: causal edge strength (${avgEdgeStrength.toFixed(2)}), graph density (${graphDensity.toFixed(2)}), query complexity, and provider reliability (${(avgProviderReliability * 100).toFixed(0)}%).`,
      confidence: Math.max(0.45, Math.min(0.95, computedConfidence)),
      confidenceFactors: {
        avgEdgeStrength: Math.round(avgEdgeStrength * 100) / 100,
        graphDensity: Math.round(graphDensity * 100) / 100,
        queryComplexity: Math.round(queryComplexity * 100) / 100,
        avgProviderReliability: Math.round(avgProviderReliability * 100) / 100,
        profilesUsed: profiles.length,
      },
      timestamp: Date.now(),
    };

    const updatedCounterfactuals = [...(model.counterfactuals as any[]), newCounterfactual];

    const [updated] = await db.update(causalModelsTable)
      .set({ counterfactuals: updatedCounterfactuals })
      .where(eq(causalModelsTable.id, modelId))
      .returning();

    return res.json({ counterfactual: newCounterfactual, model: updated });
  } catch (err) {
    return res.status(500).json({ error: "Failed to run counterfactual" });
  }
});

