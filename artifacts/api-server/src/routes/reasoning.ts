router.post("/reasoning/execute", async (req, res) => {
  try {
    const { codeId, code } = req.body;

    const targetCode = code || (codeId && (await db.select().from(generatedCodeTable).where(eq(generatedCodeTable.id, codeId)).then(r => r[0]?.code)));
    if (!targetCode) return res.status(400).json({ error: "code or codeId is required" });

    const result = await sandboxExecute(targetCode);

    if (codeId) {
      await db.update(generatedCodeTable)
        .set({
          executionResult: result,
          status: result.exitCode === 0 ? "executed" : "failed",
        })
        .where(eq(generatedCodeTable.id, codeId));
    }

    return res.json(result);
  } catch (err) {
    logger.error({ module: "reasoning-execute" }, `Execution failed: ${err}`);
    return res.status(500).json({ error: "Execution failed", details: String(err) });
  }
});

