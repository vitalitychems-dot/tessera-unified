function goalDecomposer(objective: string): { subTasks: any[]; dependencies: Record<string, string[]> } {
  const phases = [
    { id: "research", title: "Research & Analysis", description: `Analyze and gather information about: ${objective.slice(0, 80)}`, priority: 1 },
    { id: "design", title: "Design & Architecture", description: "Design the solution structure and architecture", priority: 2 },
    { id: "implement", title: "Implementation", description: "Build and implement the core components", priority: 3 },
    { id: "test", title: "Testing & Validation", description: "Test and validate the implementation", priority: 4 },
    { id: "deploy", title: "Deployment & Integration", description: "Deploy and integrate into the system", priority: 5 },
    { id: "monitor", title: "Monitoring & Iteration", description: "Monitor results and iterate on improvements", priority: 6 },
  ];
  const deps: Record<string, string[]> = {
    research: [],
    design: ["research"],
    implement: ["design"],
    test: ["implement"],
    deploy: ["test"],
    monitor: ["deploy"],
  };
  return { subTasks: phases, dependencies: deps };
}

function buildReasoningSteps(query: string): any[] {
  return [
    { step: 1, type: "observation", content: `Analyzing query: "${query.slice(0, 100)}"`, timestamp: Date.now() },
    { step: 2, type: "hypothesis", content: "Identifying key variables and relationships", timestamp: Date.now() + 100 },
    { step: 3, type: "analysis", content: "Applying multi-dimensional reasoning framework", timestamp: Date.now() + 200 },
    { step: 4, type: "validation", content: "Cross-checking intermediate conclusions", timestamp: Date.now() + 300 },
    { step: 5, type: "synthesis", content: "Synthesizing final conclusion from all reasoning steps", timestamp: Date.now() + 400 },
  ];
}

function buildCausalGraph(domain: string): { nodes: any[]; edges: any[] } {
  const nodes = [
    { id: "input", label: "Input Condition", type: "cause", description: `Initial state in ${domain}` },
    { id: "mechanism", label: "Causal Mechanism", type: "intermediate", description: "Process linking cause to effect" },
    { id: "moderator", label: "Moderating Factor", type: "moderator", description: "Variable that modifies the causal effect" },
    { id: "output", label: "Effect / Outcome", type: "effect", description: `Observable result in ${domain}` },
    { id: "feedback", label: "Feedback Loop", type: "feedback", description: "Effect that feeds back to the cause" },
  ];
  const edges = [
    { from: "input", to: "mechanism", label: "triggers", strength: 0.85 },
    { from: "mechanism", to: "output", label: "produces", strength: 0.78 },
    { from: "moderator", to: "mechanism", label: "modifies", strength: 0.62 },
    { from: "output", to: "feedback", label: "generates", strength: 0.45 },
    { from: "feedback", to: "input", label: "adjusts", strength: 0.33 },
  ];
  return { nodes, edges };
}

function generateTypeScriptCode(description: string): string {
  const fnName = description
    .toLowerCase()
    .replace(/[^a-z0-9\s]/g, "")
    .trim()
    .split(/\s+/)
    .slice(0, 3)
    .map((w, i) => i === 0 ? w : w.charAt(0).toUpperCase() + w.slice(1))
    .join("") || "processData";

  return `/**
 * ${description}
 * Generated by Tessera Reasoning Engine
 * Language: TypeScript
 */

// Type definitions
// interface InputParams { input: string; options?: Record<string, unknown>; }
// interface OutputResult { success: boolean; data: unknown; error?: string; timestamp: number; }

async function ${fnName}(params) {
  const startTime = Date.now();

  try {
    if (!params || !params.input || params.input.trim() === "") {
      throw new Error("Input cannot be empty");
    }

    // Core logic: ${description}
    const processed = params.input.trim().toUpperCase();
    const result = {
      original: params.input,
      processed,
      length: processed.length,
      wordCount: params.input.trim().split(/\\s+/).length,
      options: params.options || {},
    };

    return {
      success: true,
      data: result,
      timestamp: Date.now() - startTime,
    };
  } catch (err) {
    return {
      success: false,
      data: null,
      error: err instanceof Error ? err.message : String(err),
      timestamp: Date.now() - startTime,
    };
  }
}

// Run self-test
${fnName}({ input: "hello world", options: {} }).then(r => {
  console.log("Self-test result:", JSON.stringify(r, null, 2));
}).catch(e => {
  console.error("Self-test error:", e.message);
});
`;
}

function generateTestSuite(code: string, description: string): string {
  const fnMatch = code.match(/export async function (\w+)/);
  const fnName = fnMatch?.[1] ?? "processData";

  return `/**
 * Auto-generated tests for: ${description}
 * Generated by Tessera Reasoning Engine
 */

import { ${fnName} } from "./generated";

describe("${fnName}", () => {
  it("should succeed with valid input", async () => {
    const result = await ${fnName}({ input: "hello world" });
    expect(result.success).toBe(true);
    expect(result.data).toBeDefined();
    expect(result.error).toBeUndefined();
  });

  it("should fail with empty input", async () => {
    const result = await ${fnName}({ input: "" });
    expect(result.success).toBe(false);
    expect(result.error).toBeDefined();
  });

  it("should accept optional options", async () => {
    const result = await ${fnName}({ input: "test", options: { debug: true } });
    expect(result.success).toBe(true);
  });

  it("should return a timestamp", async () => {
    const result = await ${fnName}({ input: "test" });
    expect(typeof result.timestamp).toBe("number");
    expect(result.timestamp).toBeGreaterThanOrEqual(0);
  });

  it("should handle special characters in input", async () => {
    const result = await ${fnName}({ input: "hello! @world #test" });
    expect(result.success).toBe(true);
  });
});
`;
}

async function sandboxExecute(code: string): Promise<{ output: string; error: string | null; exitCode: number }> {
  const logs: string[] = [];
  const sandbox = {
    console: {
      log: (...args: unknown[]) => logs.push(args.map(a => typeof a === "object" ? JSON.stringify(a) : String(a)).join(" ")),
      error: (...args: unknown[]) => logs.push("[ERROR] " + args.map(a => String(a)).join(" ")),
      warn: (...args: unknown[]) => logs.push("[WARN] " + args.map(a => String(a)).join(" ")),
    },
    Math,
    JSON,
    Date,
    parseInt,
    parseFloat,
    Number,
    String,
    Boolean,
    Array,
    Object,
    Promise,
    setTimeout: (_fn: unknown, _ms: unknown) => 0,
    clearTimeout: (_id: unknown) => {},
  };

  try {
    const stripped = code
      .replace(/import\s+.*?from\s+['"][^'"]+['"];?\s*/g, "")
      .replace(/^export\s+(async\s+)?function\s+/gm, "async function ")
      .replace(/export\s+default\s+\w+;?\s*$/m, "")
      .replace(/export\s+\{[^}]+\};?\s*/g, "");

    const script = new vm.Script(stripped);
    const ctx = vm.createContext(sandbox);
    const result = script.runInContext(ctx, { timeout: 3000 });

    if (result && typeof result.then === "function") {
      await result;
    }

    return {
      output: logs.join("\n") || "(no output)",
      error: null,
      exitCode: 0,
    };
  } catch (err) {
    return {
      output: logs.join("\n"),
      error: err instanceof Error ? err.message : "Unknown error",
      exitCode: 1,
    };
  }
}

router.post("/reasoning/goals", async (req, res) => {
  try {
    const { title, objective, priority = 5 } = req.body;
    if (!objective) return res.status(400).json({ error: "objective is required" });

    const { subTasks, dependencies } = goalDecomposer(objective);

    const [goal] = await db.insert(goalsTable).values({
      title: title || objective.slice(0, 60),
      objective,
      priority,
      subTasks,
      dependencies,
      status: "active",
    }).returning();

    logger.info({ module: "reasoning-goals" }, `New goal created: ${goal.id} — ${goal.title}`);

    const rawToken = req.headers["x-admin-token"];
    const token = Array.isArray(rawToken) ? rawToken[0] : rawToken;
    const keyHash = validateMeshToken(token ?? "");
    if (keyHash) {
      meshBroadcast(keyHash, "reasoning:goal-created", {
        id: goal.id,
        title: goal.title,
        objective: goal.objective?.slice(0, 100),
        status: goal.status,
      });
    }

    return res.json(goal);
  } catch (err) {
    logger.error({ module: "reasoning-goals" }, `Failed to create goal: ${err}`);
    return res.status(500).json({ error: "Failed to create goal" });
  }
});

