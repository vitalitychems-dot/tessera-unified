export async function fetchPhysicsOverflow(limit = 10): Promise<NormalizedItem[]> {
  try {
    const data = await fetchJson<any>(
      `https://physicsoverflow.org/api/questions?filter=open&limit=${limit}`
    );
    if (!data || !Array.isArray(data.questions)) return [];
    return data.questions.map((q: any) => ({
      source: "PhysicsOverflow",
      sourceType: "problem",
      title: q.title || "Untitled",
      content: (q.body || q.description || q.title || "").slice(0, 8000),
      url: q.url || `https://physicsoverflow.org/q/${q.id}`,
      tags: ["physics", "research", ...(q.tags || [])],
      metadata: { domain: "physics" },
    }));
  } catch {
    return [];
  }
}

export async function fetchGitHubTrendingIssues(limit = 10): Promise<NormalizedItem[]> {
  try {
    const data = await fetchJson<any>(
      `https://api.github.com/search/issues?q=label%3A%22help+wanted%22+is%3Aopen+is%3Aissue+label%3A%22good+first+issue%22&sort=comments&order=desc&per_page=${limit}`,
      { "Accept": "application/vnd.github.v3+json", "User-Agent": "Tessera-Bot/1.0" }
    );
    const items: any[] = data?.items || [];
    return items.map((issue: any) => ({
      source: "GitHub Issues",
      sourceType: "problem",
      title: issue.title || "Untitled Issue",
      content: (issue.body || issue.title || "").slice(0, 8000),
      url: issue.html_url,
      tags: ["code-boundary", "github", "open-source", "help-wanted", ...(issue.labels?.map((l: any) => l.name) || [])],
      metadata: { repo: issue.repository_url?.split("/").slice(-2).join("/"), comments: issue.comments, reactions: issue.reactions?.total_count, domain: "code-boundary" },
      publishedAt: issue.created_at ? new Date(issue.created_at) : undefined,
    }));
  } catch {
    return [];
  }
}

