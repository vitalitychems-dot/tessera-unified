export async function fetchMathStackExchange(limit = 10): Promise<NormalizedItem[]> {
  try {
    const data = await fetchJson<any>(
      `https://api.stackexchange.com/2.3/questions?order=desc&sort=votes&site=math&filter=withbody&tagged=open-problem&pagesize=${limit}&key=`
    );
    const items: any[] = data?.items || [];
    return items.map((q: any) => ({
      source: "Math StackExchange",
      sourceType: "problem",
      title: q.title?.replace(/&amp;/g, "&").replace(/&lt;/g, "<").replace(/&gt;/g, ">") || "Untitled",
      content: (q.body_markdown || q.body || q.title || "").replace(/<[^>]+>/g, " ").slice(0, 8000),
      url: q.link,
      tags: ["math", "open-problem", ...(q.tags || [])],
      metadata: { score: q.score, answerCount: q.answer_count, viewCount: q.view_count, domain: "math" },
      publishedAt: q.creation_date ? new Date(q.creation_date * 1000) : undefined,
    }));
  } catch {
    return [];
  }
}

